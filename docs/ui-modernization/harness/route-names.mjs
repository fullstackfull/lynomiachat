// Regenerates `fixtures/routeNames.js` from the dashboard's own route files.
//
// The harness builds a memory router from these names so every `accountScopedRoute(name)` and
// `router.resolve({ name })` in a real component resolves. Importing the real route tree instead pulls the whole
// app graph and deadlocks on a circular import, so the list is generated rather than imported — and generated
// rather than hand-written, because a missing name silently empties a navigation section.
//
//   node docs/ui-modernization/harness/route-names.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const ROOT = 'app/javascript/dashboard';
const OUT = 'docs/ui-modernization/harness/fixtures/routeNames.js';

const walk = async dir => {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(entry => {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) return walk(path);
      return /routes?\.js$/.test(entry.name) ? [path] : [];
    })
  );
  return files.flat();
};

const names = new Set();
for (const file of await walk(ROOT)) {
  const source = await readFile(file, 'utf8');
  for (const [, name] of source.matchAll(/name:\s*'([a-z0-9_]+)'/g)) names.add(name);
}

const sorted = [...names].sort();
await writeFile(
  OUT,
  `// GENERATED by docs/ui-modernization/harness/route-names.mjs — do not edit by hand.
// The dashboard's route NAMES, scanned from every \`*.routes.js\` / \`*routes.js\` under ${ROOT}.
// The harness builds a memory router from these so every \`accountScopedRoute(name)\` and \`router.resolve({name})\`
// in a real component resolves. Importing the real route tree instead pulls the whole app graph and deadlocks on a
// circular import, so this static list is generated.
//
// Gating is deliberately permissive: the fixture user is an administrator with every feature on, so the baseline
// inventory shows the MAXIMUM control surface. That is what a parity diff should be measured against.
export const ROUTE_NAMES = [
${sorted.map(name => `  '${name}',`).join('\n')}
];
`
);
console.log(`${sorted.length} route names → ${OUT}`);
